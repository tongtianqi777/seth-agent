"""Flyers in the school's branding: a prompt becomes a PNG.

The model only reads the prompt into a FlyerSpec (what, when, where). Everything on the page, the logo, colors,
layout and every word and number, is then put there by code from the brand kit, so a date can't be misspelled and
the logo can't be redrawn. An image model, when one is set up, paints only the background, with no writing in it.
"""

from __future__ import annotations

import json
import random
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Sequence

from ..extractors.base import PermanentError, TransientError
from ..llm import LLM, Image
from .photos import Photo, PhotoError, PhotoLibrary, plan_photos
from .background import compose, scene_for
from .art import ArtError, ImageGen, plan_art, sniff_media_type
from .render import FlyerError, render_png
from .spec import FlyerSpec, extract_spec
from .design import DesignError, build_assets, design_flyer, finish_design, pick_ideas
from .template import DEFAULT_TEMPLATE, render_html

__all__ = ["ArtError", "Flyer", "FlyerError", "FlyerSpec", "Photo", "PhotoError", "PhotoLibrary", "extract_spec", "make_flyer", "render_html", "render_png"]


EXTENSIONS = {"image/png": ".png", "image/jpeg": ".jpg", "image/webp": ".webp"}


@dataclass
class Flyer:
    spec: FlyerSpec
    path: Path
    art_path: Path | None = None  # the artwork behind it, kept so the flyer can be laid out again without paying again
    art_error: str | None = None  # why there is no artwork, when it was asked for and failed
    photos: list[Photo] = field(default_factory=list)  # the library photos on the flyer
    photo_error: str | None = None  # why there are none, when they were looked for and that failed
    design: str = DEFAULT_TEMPLATE  # "creative" for a page the model designed, otherwise the layout's name
    design_error: str | None = None  # why the model's design wasn't used, when a layout took its place
    ideas: list[str] = field(default_factory=list)  # the looks the designer was pointed at
    scene: str | None = None  # the art-kit background scene used, when there was no other artwork


def make_flyer(
    llm: LLM,
    prompt: str,
    out: Path,
    brand_dir: Path,
    today: date,
    chrome: str | None = None,
    image_gen: ImageGen | None = None,
    art_file: Path | None = None,
    show_address: bool | None = None,
    library: PhotoLibrary | None = None,
    photo_count: int = 3,
    photo_ids: Sequence[int] = (),
    layout: str | None = DEFAULT_TEMPLATE,
    idea: str | None = None,
    rng: random.Random | None = None,
    design_effort: str | None = None,
    design_file: Path | None = None,
    design_max_tokens: int | None = None,
) -> Flyer:
    """Read `prompt`, lay the flyer out and save it to `out` as a PNG.

    The background is `art_file` if given, otherwise generated by `image_gen` if given, otherwise (or if that fails,
    and `art_error` says why) a scene composed from the school's art kit. A flyer always has a background.
    Photos come from `library` (the school's photo library) when they are possible and appropriate: the ones in
    `photo_ids` if given, otherwise up to `photo_count` that suit the event. The model says when photos wouldn't suit
    it (a closure, a reminder); if none are found, or finding them fails, the flyer is made without them and
    `photo_error` says why. Photos you ask for by id that can't be used are an error.
    `design_file` is a page designed elsewhere (see design.py for the tokens); it must follow the rules.
    `layout` names a fixed page design in the brand kit's templates folder. With `layout=None` the model designs the
    page itself, each time differently (`idea` steers the look); if it can't make a page that follows the school's
    rules, the standard layout is used and `design_error` says why.
    The school's address is printed when the request is for something at the school (`show_address` overrides that).
    """
    spec = extract_spec(llm, prompt, today)
    if show_address is not None:  # the person's say beats the model's reading
        spec = spec.model_copy(update={"at_school": show_address})
    photos: list[Photo] = []
    photo_error = None
    if library and photo_ids:  # the person's own choice: if one can't be used, say so
        photos = library.get(photo_ids)
    elif library and photo_count > 0:
        try:
            queries = plan_photos(llm, spec)
            photos = library.find(queries, photo_count) if queries else []
        except (PhotoError, TransientError, PermanentError) as e:
            photo_error = str(e)
    art_path, art_error, art = None, None, None
    if art_file:  # the person's own picture: if it can't be used, say so rather than quietly leaving it out
        art_path = Path(art_file)
        data = art_path.read_bytes()
        art = Image(sniff_media_type(data), data)
    elif image_gen:
        try:
            brand = json.loads((brand_dir / "brand.json").read_text())
            art = image_gen.generate(plan_art(llm, spec, brand["art"]))
        except (ArtError, TransientError, PermanentError) as e:
            art_error = str(e)
        else:
            art_path = out.with_name(f"{out.stem}-art{EXTENSIONS[art.media_type]}")
            art_path.parent.mkdir(parents=True, exist_ok=True)
            art_path.write_bytes(art.data)
    # Every flyer has a background: generated artwork or your own picture if there is one, otherwise a scene composed
    # from the school's art kit to suit the event and the season.
    scene = None if art else scene_for(spec)
    backdrop = art or compose(spec, brand_dir, scene)
    html, design, design_error, ideas = None, layout or DEFAULT_TEMPLATE, None, []
    if design_file:  # a page written by hand: held to the same rules, and an error if it breaks them
        brand = json.loads((brand_dir / "brand.json").read_text())
        assets = build_assets(spec, brand_dir, brand, backdrop, [p.image for p in photos], bool(art))
        html, design = finish_design(Path(design_file).read_text(encoding="utf-8"), assets, brand, chrome), "hand-made"
    elif layout is None:
        brand = json.loads((brand_dir / "brand.json").read_text())
        ideas = pick_ideas(rng)
        try:
            assets = build_assets(spec, brand_dir, brand, backdrop, [p.image for p in photos], bool(art))
            html = design_flyer(llm, spec, prompt, assets, brand, ideas, idea, chrome, design_effort, design_max_tokens)
            design = "creative"
        except (DesignError, TransientError, PermanentError) as e:
            design_error = str(e)
    if html is None:
        html = render_html(spec, brand_dir, backdrop, [p.image for p in photos], layout or DEFAULT_TEMPLATE)
    render_png(html, out, chrome)
    return Flyer(spec, out, art_path, art_error, photos, photo_error, design, design_error, ideas, scene)
